import numpy as np
import matplotlib.pyplot as plt
import matplotlib.animation as animation

def plot_orthogonal_views(data_3d, center=None, title="Orthogonal Views", cmap='viridis'):
    """
    Plots the three orthogonal views (Axial, Coronal, Sagittal) of a 3D Numpy array.

    Parameters:
    - data_3d: 3D numpy array (shape: Z, Y, X).
    - center: Tuple of (z, y, x) coordinates to slice through.
    - cmap: The colormap to use for the plots (default is 'viridis').
    """
    if data_3d.ndim != 3:
        raise ValueError("Input data must be a 3D array.")

    nz, ny, nx = data_3d.shape

    # Use center of volume if specific coordinates aren't provided
    if center is None:
        cz, cy, cx = nz // 2, ny // 2, nx // 2
    else:
        cz, cy, cx = center

    # Create figure and 3 axes
    fig, axes = plt.subplots(1, 3, figsize=(15, 5))
    fig.suptitle(f"{title} @ Center: ({cz}, {cy}, {cx})", fontsize=16)

    # --- View 1: Axial (XY plane, slice at fixed Z) ---
    ax1 = axes[0]
    # Slicing: [z, y, x] -> we lock z
    ax1.imshow(data_3d[cz, :, :], cmap=cmap, origin='lower', aspect='auto')
    ax1.axvline(x=cx, color='r', linestyle='--', alpha=0.7)
    ax1.axhline(y=cy, color='r', linestyle='--', alpha=0.7)
    ax1.set_title(f"Axial (Z={cz})")
    ax1.set_xlabel("X axis")
    ax1.set_ylabel("Y axis")

    # --- View 2: Coronal (XZ plane, slice at fixed Y) ---
    ax2 = axes[1]
    # Slicing: [z, y, x] -> we lock y
    ax2.imshow(data_3d[:, cy, :], cmap=cmap, origin='lower', aspect='auto')
    ax2.axvline(x=cx, color='r', linestyle='--', alpha=0.7)
    ax2.axhline(y=cz, color='r', linestyle='--', alpha=0.7)
    ax2.set_title(f"Coronal (Y={cy})")
    ax2.set_xlabel("X axis")
    ax2.set_ylabel("Z axis")

    # --- View 3: Sagittal (YZ plane, slice at fixed X) ---
    ax3 = axes[2]
    # Slicing: [z, y, x] -> we lock x
    ax3.imshow(data_3d[:, :, cx], cmap=cmap, origin='lower', aspect='auto')
    ax3.axvline(x=cy, color='r', linestyle='--', alpha=0.7)
    ax3.axhline(y=cz, color='r', linestyle='--', alpha=0.7)
    ax3.set_title(f"Sagittal (X={cx})")
    ax3.set_xlabel("Y axis")
    ax3.set_ylabel("Z axis")

    plt.tight_layout()
    plt.show()

def animate_3d_array(frames_array, fps=30, cmap='viridis', axis=False, colorbar=False, frame_text=True, vmin=None, vmax=None):
    """
    Animates a 3D numpy array where the first dimension represents time/frames.

    Args:
        frames_array (numpy.ndarray): A 3D array of shape (num_frames, height, width).
        fps (int or float): Frames per second. Determines the playback speed.
        cmap (str): Matplotlib colormap string. Default is 'viridis'. Use 'gray' for grayscale.
        axis (bool): Whether to show the X and Y coordinate axes.
        colorbar (bool): Whether to display a color scale bar alongside the animation.
        frame_text (bool): Whether to display the current frame number on the animation.
        vmin (float, optional): Minimum data value for the colormap. Auto-calculated if None.
        vmax (float, optional): Maximum data value for the colormap. Auto-calculated if None.

    Returns:
        matplotlib.animation.FuncAnimation: The animation object.
        (Keep a reference to this object so it doesn't get garbage collected).
    """
    # Ensure the array is 3D
    if frames_array.ndim != 3:
        raise ValueError(f"Expected a 3D array, but got a {frames_array.ndim}D array.")

    num_frames = frames_array.shape[0]

    # Calculate interval in milliseconds from FPS
    interval_ms = 1000.0 / fps

    # Set up the figure and axis
    fig, ax = plt.subplots()

    if not axis:
        ax.axis('off')
        fig.subplots_adjust(left=0, right=1, bottom=0, top=1) # Remove margins

    # Initialize the plot with the first frame
    # vmin and vmax ensure the color scale remains consistent across all frames
    if vmin is None:
        vmin = np.min(frames_array)
    if vmax is None:
        vmax = np.max(frames_array)

    im = ax.imshow(frames_array[0], cmap=cmap, vmin=vmin, vmax=vmax, animated=True)

    if colorbar:
        fig.colorbar(im, ax=ax)

    # Set up the text object for displaying the frame number
    text_obj = ax.text(0.02, 0.95, '', transform=ax.transAxes, color='white',
                         fontsize=12, fontweight='bold',
                         bbox=dict(facecolor='black', alpha=0.5, edgecolor='none'))

    if not frame_text:
        text_obj.set_visible(False)

    # The update function called for each frame
    def update(frame_index):
        im.set_array(frames_array[frame_index])
        if frame_text:
            text_obj.set_text(f'Frame: {frame_index}')
        # We must return all objects that have been modified so blitting works
        return [im, text_obj]

    # Create the animation
    ani = animation.FuncAnimation(
        fig,
        update,
        frames=num_frames,
        interval=interval_ms,
        blit=True,
        repeat=True
    )

    return ani
